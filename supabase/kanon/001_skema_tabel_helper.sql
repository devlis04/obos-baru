-- Tabel hanya postgres/service_role. App tidak baca kanon.
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users', 'target_sales', 'pelanggan', 'barang', 'rute_peta', 'setoran_buku',
    'lokasi_gudang', 'absensi', 'transaksi', 'transaksi_items',
    'setoran_buku_pending_foto', 'stok_opname', 'kasbon', 'kunjungan_sales',
    'kunjungan_pengirim', 'retur_toko', 'supplier', 'supplier_harga',
    'barang_masuk', 'ongkir', 'setoran_pengirim', 'setoran_kartu_simpan',
    'mutasi_bank'
  ]
  LOOP
    EXECUTE format('REVOKE ALL ON TABLE kanon.%I FROM PUBLIC, anon, authenticated', t);
    EXECUTE format(
      'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE kanon.%I TO postgres, service_role',
      t
    );
    EXECUTE format('ALTER TABLE kanon.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE kanon.%I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS kanon_postgres ON kanon.%I', t);
    EXECUTE format(
      'CREATE POLICY kanon_postgres ON kanon.%I TO postgres, service_role USING (true) WITH CHECK (true)',
      t
    );
  END LOOP;
END;
$$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA kanon TO postgres, service_role;


CREATE UNIQUE INDEX IF NOT EXISTS users_rute_satu_akun_uidx
  ON kanon.users (lower(btrim(rute)))
  WHERE btrim(rute) <> '';

CREATE OR REPLACE FUNCTION kanon.users_rapikan()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.email := lower(btrim(NEW.email));
  NEW.nama := btrim(NEW.nama);
  NEW.peran := lower(btrim(NEW.peran));
  NEW.rute := btrim(COALESCE(NEW.rute, ''));
  NEW.kunci_hp := nullif(btrim(NEW.kunci_hp), '');
  NEW.sesi_login := nullif(btrim(NEW.sesi_login), '');
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_rapikan_trg ON kanon.users;
CREATE TRIGGER users_rapikan_trg
  BEFORE INSERT OR UPDATE ON kanon.users
  FOR EACH ROW EXECUTE PROCEDURE kanon.users_rapikan();


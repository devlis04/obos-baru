  qty_masuk numeric(14, 4) NOT NULL DEFAULT 0,
  qty_packed numeric(14, 4) NOT NULL DEFAULT 0,
  qty_batal numeric(14, 4) NOT NULL DEFAULT 0,
  qty_retur numeric(14, 4) NOT NULL DEFAULT 0,
  stok_hitung numeric(14, 4) GENERATED ALWAYS AS (
    stok_awal + qty_masuk - qty_packed + qty_batal + qty_retur
  ) STORED,
  stok_fisik numeric(14, 4),
  selisih numeric(14, 4) GENERATED ALWAYS AS (
    stok_fisik - (stok_awal + qty_masuk - qty_packed + qty_batal + qty_retur)
  ) STORED,
  dicek_stok_oleh text,
  putusan text,

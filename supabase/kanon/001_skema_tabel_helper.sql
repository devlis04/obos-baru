CREATE OR REPLACE VIEW kanon.v_transaksi_item AS
SELECT
  z.*,
  z.qty_order * z.harga_jual_order AS subtotal_jual_order,
  CASE
    WHEN z.qty_packed IS NULL THEN NULL
    ELSE z.qty_packed * z.harga_jual_packed
  END AS subtotal_jual_packed,
  CASE
    WHEN z.qty_actual IS NULL THEN NULL
    ELSE z.qty_actual * z.harga_jual_actual
  END AS subtotal_jual_actual
FROM (
  SELECT
    i.id,
    i.id_transaksi,
    i.id_barang,
    i.id_grup,
    i.nama_barang,
    i.harga_beli,
    i.harga_jual,
    i.qty_order,
    i.qty_packed,
    i.qty_actual,
    i.subtotal_beli_order,
    i.subtotal_beli_packed,
    i.subtotal_beli_actual,
    i.min_strat_1,
    i.jual_strat_1,
    i.min_strat_2,
    i.jual_strat_2,
    i.min_strat_3,
    i.jual_strat_3,
    i.min_strat_4,
    i.jual_strat_4,
    i.min_strat_5,
    i.jual_strat_5,
    kanon.harga_jual_strata(
      COALESCE(i.harga_jual, 0),
      COALESCE(SUM(i.qty_order) OVER w, 0)::integer,
      i.min_strat_1, i.jual_strat_1,
      i.min_strat_2, i.jual_strat_2,
      i.min_strat_3, i.jual_strat_3,
      i.min_strat_4, i.jual_strat_4,
      i.min_strat_5, i.jual_strat_5
    ) AS harga_jual_order,
    CASE WHEN i.qty_packed IS NULL THEN NULL ELSE kanon.harga_jual_strata(
      COALESCE(i.harga_jual, 0),
      COALESCE(SUM(COALESCE(i.qty_packed, 0)) OVER w, 0)::integer,
      i.min_strat_1, i.jual_strat_1,
      i.min_strat_2, i.jual_strat_2,
      i.min_strat_3, i.jual_strat_3,
      i.min_strat_4, i.jual_strat_4,
      i.min_strat_5, i.jual_strat_5
    ) END AS harga_jual_packed,
    CASE WHEN i.qty_actual IS NULL THEN NULL ELSE kanon.harga_jual_strata(
      COALESCE(i.harga_jual, 0),
      COALESCE(SUM(COALESCE(i.qty_actual, 0)) OVER w, 0)::integer,
      i.min_strat_1, i.jual_strat_1,
      i.min_strat_2, i.jual_strat_2,
      i.min_strat_3, i.jual_strat_3,
      i.min_strat_4, i.jual_strat_4,
      i.min_strat_5, i.jual_strat_5
    ) END AS harga_jual_actual
  FROM kanon.transaksi_items i
  WINDOW w AS (
    PARTITION BY i.id_transaksi,
      COALESCE(NULLIF(btrim(i.id_grup), ''), i.id_barang)
  )
) z;

GRANT SELECT ON kanon.v_transaksi_item TO postgres, service_role;
REVOKE ALL ON kanon.v_transaksi_item FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE VIEW kanon.v_omset_nota AS
SELECT
  t.id_transaksi,
  t.id_pelanggan,
  t.nama_pelanggan,
  t.rute,
  t.status,
  t.pending,
  t.waktu_order,
  t.waktu_packed,
  t.waktu_actual,
  t.id_setoran_buku,
  coalesce(sum(i.subtotal_jual_order), 0)::bigint AS jual_order,
  coalesce(sum(i.subtotal_jual_packed), 0)::bigint AS jual_packed,
  coalesce(sum(i.subtotal_jual_actual), 0)::bigint AS jual_actual,
  kanon.omset_batal(
    t.status,
    coalesce(sum(i.subtotal_jual_packed), 0),
    coalesce(sum(i.subtotal_jual_actual), 0)
  ) AS jual_batal,
  kanon.omset_pending(
    t.pending,
    coalesce(sum(i.subtotal_jual_packed), 0)
  ) AS jual_pending,
  kanon.omset_actual(
    t.status,
    coalesce(sum(i.subtotal_jual_actual), 0)
  ) AS jual_actual_kartu
FROM kanon.transaksi t
LEFT JOIN kanon.v_transaksi_item i ON i.id_transaksi = t.id_transaksi
GROUP BY
  t.id_transaksi, t.id_pelanggan, t.nama_pelanggan, t.rute,
  t.status, t.pending, t.waktu_order, t.waktu_packed, t.waktu_actual,
  t.id_setoran_buku;

GRANT SELECT ON kanon.v_omset_nota TO postgres, service_role;
REVOKE ALL ON kanon.v_omset_nota FROM PUBLIC, anon, authenticated;


CREATE OR REPLACE FUNCTION kanon.hari_jakarta(p timestamptz)
RETURNS date
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT (p AT TIME ZONE 'Asia/Jakarta')::date;
$$;

CREATE OR REPLACE FUNCTION kanon.grup_rute(p_rute text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT regexp_replace(upper(btrim(COALESCE(p_rute, ''))), '[DH]$', '');
$$;

CREATE OR REPLACE FUNCTION kanon.harga_jual_strata(
  p_dasar integer,
  p_qty integer,
  p_min1 integer,
  p_jual1 integer,
  p_min2 integer,
  p_jual2 integer,
  p_min3 integer,
  p_jual3 integer,
  p_min4 integer,
  p_jual4 integer,
  p_min5 integer,
  p_jual5 integer
)
RETURNS integer
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT COALESCE(
    (
      SELECT s.jual
      FROM (
        VALUES
          (p_min5, p_jual5),
          (p_min4, p_jual4),
          (p_min3, p_jual3),
          (p_min2, p_jual2),
          (p_min1, p_jual1)
      ) AS s(min, jual)
      WHERE COALESCE(p_qty, 0) >= s.min
        AND s.min > 0
        AND s.jual > 0
      ORDER BY s.min DESC
      LIMIT 1
    ),
    GREATEST(COALESCE(p_dasar, 0), 0)
  );
$$;

-- Nota batal = packed penuh. Terkirim = sisa tebus (packed − actual). Selain itu 0.
CREATE OR REPLACE FUNCTION kanon.omset_batal(
  p_status text,
  p_packed numeric,
  p_actual numeric
)
RETURNS bigint
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN p_status = 'batal' THEN round(coalesce(p_packed, 0))::bigint
    WHEN p_status = 'terkirim' THEN
      greatest(round(coalesce(p_packed, 0) - coalesce(p_actual, 0)), 0)::bigint
    ELSE 0
  END;
$$;

CREATE OR REPLACE FUNCTION kanon.qty_batal(
  p_status text,
  p_packed numeric,
  p_actual numeric
)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN p_status = 'batal' THEN coalesce(p_packed, 0)
    WHEN p_status = 'terkirim' THEN
      greatest(coalesce(p_packed, 0) - coalesce(p_actual, 0), 0)
    ELSE 0
  END;
$$;

CREATE OR REPLACE FUNCTION kanon.omset_pending(
  p_pending boolean,
  p_packed numeric
)
RETURNS bigint
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN coalesce(p_pending, false) THEN round(coalesce(p_packed, 0))::bigint
    ELSE 0
  END;
$$;

CREATE OR REPLACE FUNCTION kanon.omset_actual(
  p_status text,
  p_actual numeric
)
RETURNS bigint
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN p_status = 'batal' THEN 0
    ELSE round(coalesce(p_actual, 0))::bigint
  END;
$$;

-- Admin kartu: cap buku ini, atau (buku hidup) packed belum ber-id.
-- Tidak menarik terkirim buku lain hanya karena actual hari ini.
CREATE OR REPLACE FUNCTION kanon.nota_ikut_admin(
  p_id_buku bigint,
  p_tgl date,
  p_tutup boolean,
  p_id_setoran_buku bigint,
  p_status text,
  p_waktu_actual timestamptz
)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT
    p_id_buku IS NOT NULL
    AND (
      p_id_setoran_buku = p_id_buku
      OR (
        p_id_setoran_buku IS NULL
        AND NOT coalesce(p_tutup, false)
        AND (
          p_status = 'dikirim'
          OR (
            p_status IN ('terkirim', 'batal')
            AND p_waktu_actual IS NOT NULL
            AND kanon.hari_jakarta(p_waktu_actual) = p_tgl
          )
        )
      )
    );
$$;

-- Gudang packing: cap buku, atau order hari itu belum tercap (buku hidup / belum ada buku).
CREATE OR REPLACE FUNCTION kanon.nota_ikut_gudang(
  p_id_buku bigint,
  p_tgl date,
  p_hidup boolean,
  p_id_setoran_buku bigint,
  p_waktu_order timestamptz
)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT
    p_tgl IS NOT NULL
    AND p_waktu_order IS NOT NULL
    AND (
      (p_id_buku IS NOT NULL AND p_id_setoran_buku = p_id_buku)
      OR (
        kanon.hari_jakarta(p_waktu_order) = p_tgl
        AND p_id_setoran_buku IS NULL
        AND (p_id_buku IS NULL OR coalesce(p_hidup, false))
      )
    );
$$;

CREATE OR REPLACE FUNCTION kanon.nota_ikut_pengirim(
  p_id_buku bigint,
  p_tgl date,
  p_hidup boolean,
  p_id_setoran_buku bigint,
  p_status text,
  p_waktu_order timestamptz,
  p_waktu_actual timestamptz,
  p_tanggal_lihat date
)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT
    (
      p_id_buku IS NOT NULL
      AND p_id_setoran_buku = p_id_buku
    )
    OR (
      p_tgl IS NOT NULL
      AND p_waktu_order IS NOT NULL
      AND kanon.hari_jakarta(p_waktu_order) = p_tgl
      AND p_id_setoran_buku IS NULL
      AND p_status = 'dikirim'
      AND (p_id_buku IS NULL OR coalesce(p_hidup, false))
    )
    OR (
      p_id_buku IS NULL
      AND p_id_setoran_buku IS NULL
      AND p_status IN ('terkirim', 'batal')
      AND p_waktu_actual IS NOT NULL
      AND p_tanggal_lihat IS NOT NULL
      AND kanon.hari_jakarta(p_waktu_actual) = p_tanggal_lihat
    );
$$;


CREATE OR REPLACE FUNCTION public.barang_masuk_geser_stok(p_id_barang text, p_delta numeric)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_buku bigint;
  v_tgl date;
  v_nama text;
  v_delta numeric(14, 4);
BEGIN
  v_delta := round(COALESCE(p_delta, 0), 4);
  IF v_delta = 0 OR btrim(COALESCE(p_id_barang, '')) = '' THEN
    RETURN;
  END IF;
  v_buku := public.setoran_buku_terbuka();
  IF v_buku IS NULL THEN
    PERFORM set_config('obos.boleh_tulis_stok', 'on', true);
    UPDATE public.barang
    SET stok = GREATEST(0, COALESCE(stok, 0) + v_delta)
    WHERE id_barang = p_id_barang;
    RETURN;
  END IF;

  SELECT b.tanggal INTO v_tgl FROM public.setoran_buku b WHERE b.id = v_buku;
  SELECT b.nama_barang INTO v_nama FROM public.barang b WHERE b.id_barang = p_id_barang;
  IF v_nama IS NULL THEN
    RAISE EXCEPTION 'SKU % tidak ada di katalog.', p_id_barang;
  END IF;

  INSERT INTO public.stok_opname (
    id_setoran_buku, tanggal, id_barang, nama_barang, stok_awal, qty_packed
  )
  VALUES (v_buku, v_tgl, p_id_barang, v_nama, GREATEST(0, v_delta), 0)
  ON CONFLICT (id_setoran_buku, id_barang) DO UPDATE SET
    stok_awal = GREATEST(0, public.stok_opname.stok_awal + v_delta),
    stok_fisik = CASE
      WHEN public.stok_opname.stok_fisik IS NULL THEN NULL
      ELSE GREATEST(0, public.stok_opname.stok_fisik + v_delta)
    END;
END;
$$;

CREATE OR REPLACE FUNCTION public.barang_masuk_terapkan_harga(
  p_id_supplier integer,
  p_id_barang text,
  p_harga numeric
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_kat integer;
  v_utama integer;
BEGIN
  v_kat := (round(GREATEST(COALESCE(p_harga, 0), 0) / 5) * 5)::integer;
  IF v_kat < 1 THEN
    RETURN 0;
  END IF;
  INSERT INTO public.supplier_harga (id_supplier, id_barang, harga_beli)
  VALUES (p_id_supplier, p_id_barang, v_kat)
  ON CONFLICT (id_supplier, id_barang) DO UPDATE SET
    harga_beli = EXCLUDED.harga_beli;

  SELECT b.id_supplier_utama INTO v_utama
  FROM public.barang b
  WHERE b.id_barang = p_id_barang;

  IF v_utama IS NULL THEN
    UPDATE public.barang
    SET
      id_supplier_utama = p_id_supplier,
      harga_beli = GREATEST(harga_beli, v_kat),
      harga_jual = CASE
        WHEN GREATEST(harga_beli, v_kat) <> harga_beli
          OR harga_jual < 1
        THEN public.jual_dari_modal(GREATEST(harga_beli, v_kat))
        ELSE harga_jual
      END
    WHERE id_barang = p_id_barang;
  ELSIF v_utama = p_id_supplier THEN
    UPDATE public.barang
    SET
      harga_beli = GREATEST(harga_beli, v_kat),
      harga_jual = CASE
        WHEN GREATEST(harga_beli, v_kat) > harga_beli
        THEN public.jual_dari_modal(GREATEST(harga_beli, v_kat))
        ELSE harga_jual
      END
    WHERE id_barang = p_id_barang;
  END IF;
  RETURN v_kat;
END;
$$;


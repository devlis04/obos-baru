CREATE OR REPLACE FUNCTION public.admin_ongkir_simpan(p_id_supplier integer, p_jumlah integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_buku bigint;
  v_tgl date;
  v_jml integer;
BEGIN
  IF NOT public.admin_sedang_login() THEN
    RAISE EXCEPTION 'Hanya admin yang boleh menyimpan ongkir.';
  END IF;
  IF COALESCE(p_id_supplier, 0) < 1 THEN
    RAISE EXCEPTION 'Pilih supplier.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.supplier s WHERE s.id = p_id_supplier AND s.aktif) THEN
    RAISE EXCEPTION 'Supplier tidak aktif.';
  END IF;
  v_jml := GREATEST(COALESCE(p_jumlah, 0), 0);
  SELECT o_buku, o_tgl INTO v_buku, v_tgl FROM public.barang_masuk_lingkup();
  IF v_jml = 0 THEN
    DELETE FROM public.ongkir o
    WHERE o.id_supplier = p_id_supplier
      AND (
        (v_buku IS NOT NULL AND o.id_setoran_buku = v_buku)
        OR (v_buku IS NULL AND o.id_setoran_buku IS NULL AND o.tanggal = v_tgl)
      );
    RETURN;
  END IF;
  IF v_buku IS NOT NULL THEN
    INSERT INTO public.ongkir (tanggal, id_supplier, jumlah, id_setoran_buku)
    VALUES (v_tgl, p_id_supplier, v_jml, v_buku)
    ON CONFLICT (id_setoran_buku, id_supplier) WHERE id_setoran_buku IS NOT NULL
    DO UPDATE SET jumlah = EXCLUDED.jumlah;
  ELSE
    INSERT INTO public.ongkir (tanggal, id_supplier, jumlah, id_setoran_buku)
    VALUES (v_tgl, p_id_supplier, v_jml, NULL)
    ON CONFLICT (tanggal, id_supplier) WHERE id_setoran_buku IS NULL
    DO UPDATE SET jumlah = EXCLUDED.jumlah;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_barang_masuk_simpan(
  p_id_supplier integer,
  p_baris jsonb,
  p_ongkir integer DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  r jsonb;
  v_buku bigint;
  v_tgl date;
  v_kode text;
  v_kode_in text;
  v_nama text;
  v_nama_dasar text;
  v_satuan text;
  v_rincian text;
  v_kategori text;
  v_qty numeric(14, 4);
  v_harga numeric;
  v_nilai integer;
  v_baru boolean;
  v_n integer := 0;
BEGIN
  IF NOT public.admin_sedang_login() THEN
    RAISE EXCEPTION 'Hanya admin yang boleh menyimpan barang masuk.';
  END IF;
  IF COALESCE(p_id_supplier, 0) < 1 THEN
    RAISE EXCEPTION 'Pilih supplier.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.supplier s WHERE s.id = p_id_supplier AND s.aktif) THEN
    RAISE EXCEPTION 'Supplier tidak aktif.';
  END IF;
  IF p_baris IS NULL OR jsonb_typeof(p_baris) <> 'array' THEN
    RAISE EXCEPTION 'Daftar barang wajib.';
  END IF;

  PERFORM pg_advisory_xact_lock(88221020);
  SELECT o_buku, o_tgl INTO v_buku, v_tgl FROM public.barang_masuk_lingkup();

  FOR r IN SELECT value FROM jsonb_array_elements(p_baris)
  LOOP
    v_baru := COALESCE((r ->> 'baru')::boolean, false);
    v_kode := nullif(btrim(COALESCE(r ->> 'id_barang', r ->> 'kode_barang', '')), '');
    v_nama_dasar := btrim(COALESCE(r ->> 'nama', ''));
    v_satuan := btrim(COALESCE(r ->> 'satuan', ''));
    v_rincian := btrim(COALESCE(r ->> 'rincian', ''));
    v_kategori := btrim(COALESCE(r ->> 'kategori', ''));
    v_qty := round(GREATEST(COALESCE(replace(btrim(COALESCE(r ->> 'qty', '')), ',', '.')::numeric, 0), 0), 4);
    v_harga := GREATEST(COALESCE(replace(btrim(COALESCE(r ->> 'harga_beli', '')), ',', '.')::numeric, 0), 0);
    IF v_qty <= 0 OR v_harga <= 0 THEN
      CONTINUE;
    END IF;
    v_nilai := round(v_qty * v_harga)::integer;

    IF v_baru THEN
      IF v_nama_dasar = '' OR v_satuan = '' THEN
        RAISE EXCEPTION 'SKU baru wajib nama dan satuan.';
      END IF;
      v_nama := v_nama_dasar || ' /' || v_satuan;
      IF v_rincian <> '' THEN
        v_nama := v_nama || '/' || v_rincian;
      END IF;
      v_kode := public.barang_id_berikut();
      INSERT INTO public.barang (
        id_barang, nama_barang, kategori, stok, harga_beli, harga_jual, id_supplier_utama
      )
      VALUES (
        v_kode,
        v_nama,
        nullif(v_kategori, ''),
        0,
        0,
        0,
        p_id_supplier
      );
    ELSE
      IF v_kode IS NULL THEN
        RAISE EXCEPTION 'Kode barang kosong.';
      END IF;
      v_kode_in := v_kode;
      SELECT b.id_barang INTO v_kode
      FROM public.barang b
      WHERE lower(b.id_barang) = lower(v_kode_in);
      IF v_kode IS NULL THEN
        RAISE EXCEPTION 'Kode % tidak ada di katalog. SKU baru isi di form SKU baru.', v_kode_in;
      END IF;
    END IF;

    PERFORM public.barang_masuk_geser_stok(v_kode, v_qty);
    PERFORM public.barang_masuk_terapkan_harga(p_id_supplier, v_kode, v_harga);

    IF v_buku IS NOT NULL THEN
      INSERT INTO public.barang_masuk (
        tanggal, id_supplier, id_barang, qty, nilai, id_setoran_buku
      )
      VALUES (v_tgl, p_id_supplier, v_kode, v_qty, v_nilai, v_buku)
      ON CONFLICT (id_setoran_buku, id_supplier, id_barang)
      WHERE id_setoran_buku IS NOT NULL
      DO UPDATE SET
        qty = public.barang_masuk.qty + EXCLUDED.qty,
        nilai = public.barang_masuk.nilai + EXCLUDED.nilai;
    ELSE
      INSERT INTO public.barang_masuk (
        tanggal, id_supplier, id_barang, qty, nilai, id_setoran_buku
      )
      VALUES (v_tgl, p_id_supplier, v_kode, v_qty, v_nilai, NULL)
      ON CONFLICT (tanggal, id_supplier, id_barang)
      WHERE id_setoran_buku IS NULL
      DO UPDATE SET
        qty = public.barang_masuk.qty + EXCLUDED.qty,
        nilai = public.barang_masuk.nilai + EXCLUDED.nilai;
    END IF;
    v_n := v_n + 1;
  END LOOP;

  IF p_ongkir IS NOT NULL THEN
    PERFORM public.admin_ongkir_simpan(p_id_supplier, p_ongkir);
  END IF;
  RETURN v_n;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_barang_masuk_ubah(
  p_id_supplier integer,
  p_id_barang text,
  p_qty numeric,
  p_harga_beli numeric
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_buku bigint;
  v_tgl date;
  v_kode text;
  v_qty numeric(14, 4);
  v_lama numeric(14, 4);
  v_harga numeric;
  v_nilai integer;
BEGIN
  IF NOT public.admin_sedang_login() THEN
    RAISE EXCEPTION 'Hanya admin yang boleh mengubah barang masuk.';
  END IF;
  v_kode := nullif(btrim(COALESCE(p_id_barang, '')), '');
  v_qty := round(GREATEST(COALESCE(p_qty, 0), 0), 4);
  v_harga := GREATEST(COALESCE(p_harga_beli, 0), 0);
  IF COALESCE(p_id_supplier, 0) < 1 OR v_kode IS NULL OR v_qty <= 0 OR v_harga <= 0 THEN
    RAISE EXCEPTION 'Qty dan harga beli wajib lebih dari nol.';
  END IF;

  PERFORM pg_advisory_xact_lock(88221020);
  SELECT o_buku, o_tgl INTO v_buku, v_tgl FROM public.barang_masuk_lingkup();

  SELECT m.qty INTO v_lama
  FROM public.barang_masuk m
  WHERE m.id_supplier = p_id_supplier
    AND m.id_barang = v_kode
    AND (
      (v_buku IS NOT NULL AND m.id_setoran_buku = v_buku)
      OR (v_buku IS NULL AND m.id_setoran_buku IS NULL AND m.tanggal = v_tgl)
    )
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Baris barang masuk tidak ada.';
  END IF;

  v_nilai := round(v_qty * v_harga)::integer;
  PERFORM public.barang_masuk_geser_stok(v_kode, v_qty - v_lama);
  PERFORM public.barang_masuk_terapkan_harga(p_id_supplier, v_kode, v_harga);

  UPDATE public.barang_masuk m
  SET qty = v_qty, nilai = v_nilai
  WHERE m.id_supplier = p_id_supplier
    AND m.id_barang = v_kode
    AND (
      (v_buku IS NOT NULL AND m.id_setoran_buku = v_buku)
      OR (v_buku IS NULL AND m.id_setoran_buku IS NULL AND m.tanggal = v_tgl)
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_barang_masuk_hapus(
  p_id_supplier integer,
  p_id_barang text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_buku bigint;
  v_tgl date;
  v_kode text;
  v_lama numeric(14, 4);
BEGIN
  IF NOT public.admin_sedang_login() THEN
    RAISE EXCEPTION 'Hanya admin yang boleh menghapus barang masuk.';
  END IF;
  v_kode := nullif(btrim(COALESCE(p_id_barang, '')), '');
  IF COALESCE(p_id_supplier, 0) < 1 OR v_kode IS NULL THEN
    RAISE EXCEPTION 'SKU kosong.';
  END IF;

  PERFORM pg_advisory_xact_lock(88221020);
  SELECT o_buku, o_tgl INTO v_buku, v_tgl FROM public.barang_masuk_lingkup();

  SELECT m.qty INTO v_lama
  FROM public.barang_masuk m
  WHERE m.id_supplier = p_id_supplier
    AND m.id_barang = v_kode
    AND (
      (v_buku IS NOT NULL AND m.id_setoran_buku = v_buku)
      OR (v_buku IS NULL AND m.id_setoran_buku IS NULL AND m.tanggal = v_tgl)
    )
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Baris barang masuk tidak ada.';
  END IF;

  PERFORM public.barang_masuk_geser_stok(v_kode, -v_lama);
  DELETE FROM public.barang_masuk m
  WHERE m.id_supplier = p_id_supplier
    AND m.id_barang = v_kode
    AND (
      (v_buku IS NOT NULL AND m.id_setoran_buku = v_buku)
      OR (v_buku IS NULL AND m.id_setoran_buku IS NULL AND m.tanggal = v_tgl)
    );
END;
$$;


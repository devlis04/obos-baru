CREATE OR REPLACE FUNCTION public.jual_dari_modal(p_beli integer)
RETURNS integer
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  v integer;
BEGIN
  IF COALESCE(p_beli, 0) <= 0 THEN
    RETURN 0;
  END IF;
  v := (round(p_beli::numeric * 1.05 / 500) * 500)::integer;
  IF v <= p_beli THEN
    v := (p_beli / 500 + 1) * 500;
  END IF;
  RETURN v;
END;
$$;

CREATE OR REPLACE FUNCTION public.barang_id_berikut()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_id text;
  v_pre text;
  v_num text;
  v_next integer;
BEGIN
  PERFORM pg_advisory_xact_lock(88112001);
  SELECT b.id_barang
  INTO v_id
  FROM public.barang b
  WHERE b.id_barang ~ '^[A-Za-z]+[0-9]+$'
  ORDER BY substring(b.id_barang from '([0-9]+)$')::integer DESC, b.id_barang DESC
  LIMIT 1;
  IF v_id IS NULL OR v_id !~ '^[A-Za-z]+[0-9]+$' THEN
    RETURN 'BR001';
  END IF;
  v_pre := substring(v_id from '^([A-Za-z]+)');
  v_num := substring(v_id from '([0-9]+)$');
  v_next := v_num::integer + 1;
  RETURN v_pre || lpad(v_next::text, GREATEST(length(v_num), length(v_next::text)), '0');
END;
$$;


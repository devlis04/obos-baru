-- Klaim retur pengirim per toko per buku. Stok langsung seperti batal
-- (stok_kembali_packing). Tidak menunggu cek fisik admin.
-- Jalankan SETELAH 038 dan 039. Boleh diulang.

CREATE TABLE IF NOT EXISTS public.retur_toko (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_setoran_buku bigint NOT NULL REFERENCES public.setoran_buku (id),
  tanggal date NOT NULL,
  rute_pengirim text NOT NULL,
  id_pelanggan text NOT NULL,
  kode_barang text NOT NULL,
  nama_barang text NOT NULL DEFAULT '',
  qty integer NOT NULL,
  harga_jual integer NOT NULL DEFAULT 0,
  waktu_catat timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT retur_toko_qty_chk CHECK (qty > 0),
  CONSTRAINT retur_toko_harga_chk CHECK (harga_jual >= 0),
  CONSTRAINT retur_toko_rute_chk CHECK (btrim(rute_pengirim) <> ''),
  CONSTRAINT retur_toko_toko_chk CHECK (btrim(id_pelanggan) <> ''),
  CONSTRAINT retur_toko_sku_chk CHECK (btrim(kode_barang) <> '')
);

COMMENT ON TABLE public.retur_toko IS
  'Klaim retur pengirim. Bukan tebus nota. Stok geser saat simpan, seperti batal.';

CREATE UNIQUE INDEX IF NOT EXISTS retur_toko_buku_uidx
  ON public.retur_toko (id_setoran_buku, rute_pengirim, id_pelanggan, kode_barang);
CREATE INDEX IF NOT EXISTS retur_toko_buku_idx
  ON public.retur_toko (id_setoran_buku);
CREATE INDEX IF NOT EXISTS retur_toko_rute_idx
  ON public.retur_toko (rute_pengirim, tanggal);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.retur_toko
  TO postgres, service_role;
GRANT SELECT ON TABLE public.retur_toko TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON TABLE public.retur_toko FROM authenticated;
REVOKE ALL ON TABLE public.retur_toko FROM anon;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO postgres, service_role;


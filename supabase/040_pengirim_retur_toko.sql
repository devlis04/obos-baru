-- Balikkan stok_kembali_packing (batal/retur dibatalkan).
CREATE OR REPLACE FUNCTION public.stok_balik_dari_packing(
  p_id_barang text,
  p_qty numeric
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_buku bigint;
  v_qty numeric(14, 4);
  v_fisik numeric(14, 4);
BEGIN
  v_qty := round(GREATEST(COALESCE(p_qty, 0), 0), 4);
  IF v_qty = 0 OR btrim(COALESCE(p_id_barang, '')) = '' THEN
    RETURN;
  END IF;

  v_buku := public.setoran_buku_terbuka();
  IF v_buku IS NULL THEN
    PERFORM set_config('obos.boleh_tulis_stok', 'on', true);
    UPDATE public.barang
    SET stok = GREATEST(COALESCE(stok, 0) - v_qty, 0)
    WHERE id_barang = p_id_barang;
    RETURN;
  END IF;

  SELECT so.stok_fisik INTO v_fisik
  FROM public.stok_opname so
  WHERE so.id_setoran_buku = v_buku
    AND so.id_barang = p_id_barang
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  UPDATE public.stok_opname
  SET
    qty_packed = qty_packed + v_qty,
    stok_fisik = CASE
      WHEN stok_fisik IS NULL THEN NULL
      ELSE GREATEST(stok_fisik - v_qty, 0)
    END
  WHERE id_setoran_buku = v_buku
    AND id_barang = p_id_barang;
END;
$$;

REVOKE ALL ON FUNCTION public.stok_balik_dari_packing(text, numeric) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.stok_balik_dari_packing(text, numeric)
  TO postgres, service_role;

CREATE OR REPLACE FUNCTION public.pengirim_buku_hari(p_tanggal date)
RETURNS bigint
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_hari date;
  v_today date;
  v_id bigint;
  v_tgl date;
BEGIN
  v_hari := p_tanggal;
  v_today := (timezone('Asia/Jakarta', clock_timestamp()))::date;
  SELECT b.id, b.tanggal INTO v_id, v_tgl
  FROM public.setoran_buku b
  WHERE NOT b.ditutup
  LIMIT 1;
  IF v_id IS NOT NULL AND (v_hari = v_today OR v_hari = v_tgl) THEN
    RETURN v_id;
  END IF;
  SELECT b.id INTO v_id
  FROM public.setoran_buku b
  WHERE b.tanggal = v_hari
  ORDER BY b.id DESC
  LIMIT 1;
  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.pengirim_buku_hari(date) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pengirim_buku_hari(date)
  TO authenticated, postgres, service_role;

CREATE OR REPLACE FUNCTION public.pengirim_barang_cari(p_cari text)
RETURNS TABLE (
  kode_barang text,
  nama_barang text,
  harga_jual integer
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_q text;
BEGIN
  IF NOT public.pengirim_sedang_login() THEN
    RETURN;
  END IF;
  v_q := btrim(COALESCE(p_cari, ''));
  IF char_length(v_q) < 2 THEN
    RETURN;
  END IF;
  v_q := '%' || replace(replace(v_q, '%', ''), '_', '') || '%';
  RETURN QUERY
  SELECT
    b.id_barang,
    COALESCE(NULLIF(btrim(b.nama_barang), ''), b.id_barang),
    COALESCE(b.harga_jual, 0)::integer
  FROM public.barang b
  WHERE b.id_barang ILIKE v_q OR b.nama_barang ILIKE v_q
  ORDER BY b.nama_barang
  LIMIT 30;
END;
$$;

CREATE OR REPLACE FUNCTION public.pengirim_retur_dikunci(p_tanggal date)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_rute text;
  v_buku bigint;
BEGIN
  IF NOT public.pengirim_sedang_login() OR p_tanggal IS NULL THEN
    RETURN true;
  END IF;
  v_rute := public.pengirim_grup_rute(public.pengirim_rute_saya());
  v_buku := public.pengirim_buku_hari(p_tanggal);
  IF v_rute IS NULL OR v_buku IS NULL THEN
    RETURN true;
  END IF;
  RETURN EXISTS (
    SELECT 1 FROM public.setoran_pengirim s
    WHERE s.rute_pengirim = v_rute
      AND s.id_setoran_buku = v_buku
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.pengirim_retur_toko_lihat(
  p_tanggal date,
  p_id_pelanggan text
)
RETURNS TABLE (
  kode_barang text,
  nama_barang text,
  qty integer,
  harga_jual integer,
  nilai integer,
  dikunci boolean
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_rute text;
  v_id text;
  v_buku bigint;
  v_kunci boolean;
BEGIN
  IF NOT public.pengirim_sedang_login() OR p_tanggal IS NULL THEN
    RETURN;
  END IF;
  v_rute := public.pengirim_grup_rute(public.pengirim_rute_saya());
  v_id := nullif(btrim(COALESCE(p_id_pelanggan, '')), '');
  v_buku := public.pengirim_buku_hari(p_tanggal);
  IF v_rute IS NULL OR v_id IS NULL OR v_buku IS NULL THEN
    RETURN;
  END IF;
  v_kunci := public.pengirim_retur_dikunci(p_tanggal);
  RETURN QUERY
  SELECT
    i.kode_barang,
    COALESCE(NULLIF(btrim(i.nama_barang), ''), i.kode_barang),
    i.qty,
    i.harga_jual,
    (i.qty * i.harga_jual)::integer,
    v_kunci
  FROM public.retur_toko i
  WHERE i.id_setoran_buku = v_buku
    AND i.rute_pengirim = v_rute
    AND i.id_pelanggan = v_id
  ORDER BY 2;
END;
$$;

CREATE OR REPLACE FUNCTION public.pengirim_retur_rute_lihat(p_tanggal date)
RETURNS TABLE (
  id_pelanggan text,
  nama_toko text,
  kode_barang text,
  nama_barang text,
  qty integer,
  nilai integer

-- Putusan selisih opname: kasbon / beban / margin plus.
-- Plus otomatis ke pool gaji saat tutup buku. Minus wajib diputuskan dulu.
-- Jalankan SETELAH 019. Boleh diulang.

ALTER TABLE public.stok_opname
  ADD COLUMN IF NOT EXISTS putusan text,
  ADD COLUMN IF NOT EXISTS nilai_putusan integer,
  ADD COLUMN IF NOT EXISTS harga_beli_putusan integer,
  ADD COLUMN IF NOT EXISTS qty_selisih_putusan numeric(14, 4),
  ADD COLUMN IF NOT EXISTS kasbon_email text,
  ADD COLUMN IF NOT EXISTS kasbon_nama text,
  ADD COLUMN IF NOT EXISTS waktu_putusan timestamptz;

ALTER TABLE public.stok_opname
  DROP CONSTRAINT IF EXISTS stok_opname_putusan_chk;
ALTER TABLE public.stok_opname
  ADD CONSTRAINT stok_opname_putusan_chk CHECK (
    putusan IS NULL
    OR (
      putusan IN ('kasbon', 'beban', 'margin_plus')
      AND nilai_putusan IS NOT NULL
      AND nilai_putusan >= 0
      AND harga_beli_putusan IS NOT NULL
      AND harga_beli_putusan >= 0
      AND (
        putusan <> 'kasbon'
        OR (
          kasbon_email IS NOT NULL
          AND btrim(kasbon_email) <> ''
          AND kasbon_nama IS NOT NULL
          AND btrim(kasbon_nama) <> ''
        )
      )
    )
  );

COMMENT ON COLUMN public.stok_opname.putusan IS
  'kasbon = utang karyawan. beban = potong margin gaji. margin_plus = tambah margin gaji.';

CREATE TABLE IF NOT EXISTS public.kasbon (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL REFERENCES public.users (email),
  nama text NOT NULL,
  nilai integer NOT NULL,
  id_setoran_buku bigint NOT NULL REFERENCES public.setoran_buku (id),
  id_barang text NOT NULL,
  waktu timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT kasbon_nilai_chk CHECK (nilai > 0),
  CONSTRAINT kasbon_nama_chk CHECK (btrim(nama) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS kasbon_buku_sku_uidx
  ON public.kasbon (id_setoran_buku, id_barang);
CREATE INDEX IF NOT EXISTS kasbon_email_idx
  ON public.kasbon (email, waktu DESC);

COMMENT ON TABLE public.kasbon IS
  'Utang karyawan dari selisih opname kurang. Satu baris per SKU per buku.';

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.kasbon
  TO postgres, service_role;
GRANT SELECT ON TABLE public.kasbon TO authenticated;
REVOKE ALL ON TABLE public.kasbon FROM anon;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO postgres, service_role;

ALTER TABLE public.kasbon ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kasbon FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS kasbon_select_admin ON public.kasbon;
CREATE POLICY kasbon_select_admin
  ON public.kasbon
  FOR SELECT
  TO authenticated
  USING (public.admin_sedang_login());

CREATE OR REPLACE FUNCTION public.stok_opname_bersih_putusan()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.putusan IS NULL THEN
    RETURN NEW;
  END IF;
  IF NEW.selisih IS DISTINCT FROM OLD.selisih
     OR NEW.stok_fisik IS DISTINCT FROM OLD.stok_fisik THEN
    DELETE FROM public.kasbon k
    WHERE k.id_setoran_buku = NEW.id_setoran_buku
      AND k.id_barang = NEW.id_barang;
    NEW.putusan := NULL;
    NEW.nilai_putusan := NULL;
    NEW.harga_beli_putusan := NULL;
    NEW.qty_selisih_putusan := NULL;
    NEW.kasbon_email := NULL;
    NEW.kasbon_nama := NULL;
    NEW.waktu_putusan := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS stok_opname_bersih_putusan_trg ON public.stok_opname;
CREATE TRIGGER stok_opname_bersih_putusan_trg
  BEFORE UPDATE OF stok_fisik, qty_packed, stok_awal ON public.stok_opname
  FOR EACH ROW
  EXECUTE PROCEDURE public.stok_opname_bersih_putusan();

CREATE OR REPLACE FUNCTION public.admin_users_kasbon()
RETURNS TABLE (email text, nama text, peran text)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
BEGIN
  IF NOT public.admin_sedang_login() THEN
    RAISE EXCEPTION 'Hanya akun admin yang boleh masuk web ini.';

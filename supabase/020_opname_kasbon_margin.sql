CREATE OR REPLACE FUNCTION public.admin_opname_putusan(
  p_id_setoran_buku bigint,
  p_id_barang text,
  p_jenis text,
  p_email text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_tutup boolean;
  v_jenis text;
  v_sku text;
  v_selisih numeric;
  v_harga integer;
  v_nilai integer;
  v_email text;
  v_nama text;
BEGIN
  IF NOT public.admin_sedang_login() THEN
    RAISE EXCEPTION 'Hanya admin yang boleh memutuskan selisih.';
  END IF;
  IF p_id_setoran_buku IS NULL OR btrim(COALESCE(p_id_barang, '')) = '' THEN
    RAISE EXCEPTION 'Buku atau SKU kosong.';
  END IF;

  v_jenis := lower(btrim(COALESCE(p_jenis, '')));
  IF v_jenis NOT IN ('kasbon', 'beban') THEN
    RAISE EXCEPTION 'Jenis putusan wajib kasbon atau beban.';
  END IF;

  SELECT b.ditutup INTO v_tutup
  FROM public.setoran_buku b
  WHERE b.id = p_id_setoran_buku;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Buku tidak ada.';
  END IF;
  IF COALESCE(v_tutup, false) THEN
    RAISE EXCEPTION 'Buku sudah ditutup.';
  END IF;

  PERFORM pg_advisory_xact_lock(88221019);

  SELECT so.id_barang, so.selisih, GREATEST(COALESCE(b.harga_beli, 0), 0)::integer
  INTO v_sku, v_selisih, v_harga
  FROM public.stok_opname so
  LEFT JOIN public.barang b ON b.id_barang = so.id_barang
  WHERE so.id_setoran_buku = p_id_setoran_buku
    AND so.id_barang = btrim(p_id_barang);
  IF v_sku IS NULL THEN
    RAISE EXCEPTION 'SKU tidak ada di buku ini.';
  END IF;
  IF v_selisih IS NULL OR v_selisih >= 0 THEN
    RAISE EXCEPTION 'Hanya selisih kurang yang dipilih kasbon atau beban.';
  END IF;

  v_nilai := round(abs(v_selisih) * v_harga)::integer;

  IF v_jenis = 'kasbon' THEN
    v_email := lower(btrim(COALESCE(p_email, '')));
    IF v_email = '' THEN
      RAISE EXCEPTION 'Pilih karyawan untuk kasbon.';
    END IF;
    SELECT u.nama INTO v_nama
    FROM public.users u
    WHERE u.email = v_email;
    IF v_nama IS NULL THEN
      RAISE EXCEPTION 'Karyawan tidak ada.';
    END IF;
    IF v_nilai < 1 THEN
      RAISE EXCEPTION 'Nilai kasbon harus lebih dari nol. Cek harga beli.';
    END IF;
  ELSE
    v_email := NULL;
    v_nama := NULL;
  END IF;

  UPDATE public.stok_opname
  SET
    putusan = v_jenis,
    nilai_putusan = v_nilai,
    harga_beli_putusan = v_harga,
    qty_selisih_putusan = v_selisih,
    kasbon_email = v_email,
    kasbon_nama = v_nama,
    waktu_putusan = clock_timestamp()
  WHERE id_setoran_buku = p_id_setoran_buku
    AND id_barang = v_sku;

  DELETE FROM public.kasbon
  WHERE id_setoran_buku = p_id_setoran_buku
    AND id_barang = v_sku;

  IF v_jenis = 'kasbon' THEN
    INSERT INTO public.kasbon (
      email, nama, nilai, id_setoran_buku, id_barang
    ) VALUES (
      v_email, v_nama, v_nilai, p_id_setoran_buku, v_sku
    );
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_opname_ringkas()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_id bigint;
  v_tgl date;
  v_tutup boolean;
  v_total integer := 0;
  v_fisik integer := 0;
  v_selisih integer := 0;
  v_nilai bigint := 0;
  v_minus_belum integer := 0;
  v_kasbon bigint := 0;
  v_beban bigint := 0;
  v_plus bigint := 0;
BEGIN
  IF NOT public.admin_sedang_login() THEN
    RAISE EXCEPTION 'Hanya akun admin yang boleh masuk web ini.';
  END IF;

  v_id := public.setoran_buku_terbuka();
  IF v_id IS NULL THEN
    SELECT b.id, b.tanggal, b.ditutup
    INTO v_id, v_tgl, v_tutup
    FROM public.setoran_buku b
    ORDER BY b.id DESC
    LIMIT 1;
  ELSE
    SELECT b.tanggal, b.ditutup
    INTO v_tgl, v_tutup
    FROM public.setoran_buku b
    WHERE b.id = v_id;
  END IF;

  IF v_id IS NULL THEN
    RETURN jsonb_build_object(
      'ada_buku', false,
      'id_setoran_buku', NULL,
      'tanggal', NULL,
      'ditutup', false,
      'sku_total', 0,
      'sku_fisik', 0,
      'sku_selisih', 0,
      'nilai_selisih', 0,
      'sku_minus_belum', 0,
      'nilai_kasbon', 0,
      'nilai_beban', 0,
      'nilai_margin_plus', 0
    );
  END IF;

  SELECT
    count(*)::integer,
    count(*) FILTER (WHERE so.stok_fisik IS NOT NULL)::integer,
    count(*) FILTER (
      WHERE so.stok_fisik IS NOT NULL AND COALESCE(so.selisih, 0) <> 0
    )::integer,
    coalesce(sum(
      CASE
        WHEN so.stok_fisik IS NULL THEN 0
        ELSE round(COALESCE(so.selisih, 0) * COALESCE(b.harga_beli, 0))
      END
    ), 0)::bigint,
    count(*) FILTER (
      WHERE so.stok_fisik IS NOT NULL
        AND COALESCE(so.selisih, 0) < 0
        AND so.putusan IS DISTINCT FROM 'kasbon'
        AND so.putusan IS DISTINCT FROM 'beban'
    )::integer,
    coalesce(sum(so.nilai_putusan) FILTER (WHERE so.putusan = 'kasbon'), 0)::bigint,
    coalesce(sum(so.nilai_putusan) FILTER (WHERE so.putusan = 'beban'), 0)::bigint,
    coalesce(sum(
      CASE
        WHEN so.stok_fisik IS NOT NULL AND COALESCE(so.selisih, 0) > 0
          THEN round(so.selisih * COALESCE(b.harga_beli, 0))
        ELSE 0
      END
    ), 0)::bigint
  INTO v_total, v_fisik, v_selisih, v_nilai, v_minus_belum, v_kasbon, v_beban, v_plus
  FROM public.stok_opname so
  LEFT JOIN public.barang b ON b.id_barang = so.id_barang
  WHERE so.id_setoran_buku = v_id;

  RETURN jsonb_build_object(
    'ada_buku', true,
    'id_setoran_buku', v_id,
    'tanggal', v_tgl,
    'ditutup', COALESCE(v_tutup, false),
    'sku_total', v_total,
    'sku_fisik', v_fisik,
    'sku_selisih', v_selisih,
    'nilai_selisih', v_nilai,
    'sku_minus_belum', v_minus_belum,
    'nilai_kasbon', v_kasbon,
    'nilai_beban', v_beban,
    'nilai_margin_plus', v_plus
  );
END;
$$;


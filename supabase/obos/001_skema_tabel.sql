-- Hanya postgres/service_role. App tetap public.
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users', 'lokasi_gudang', 'rute_peta', 'supplier', 'target_sales',
    'pelanggan', 'barang', 'supplier_harga', 'setoran_buku', 'absensi',
    'transaksi', 'transaksi_items', 'setoran_buku_pending_foto', 'stok_opname',
    'kasbon', 'kunjungan_sales', 'kunjungan_pengirim', 'retur_toko',
    'barang_masuk', 'ongkir', 'setoran_pengirim', 'setoran_kartu_simpan',
    'mutasi_bank'
  ]
  LOOP
    EXECUTE format('REVOKE ALL ON TABLE obos.%I FROM PUBLIC, anon, authenticated', t);
    EXECUTE format(
      'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE obos.%I TO postgres, service_role',
      t
    );
    EXECUTE format('ALTER TABLE obos.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE obos.%I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY obos_postgres ON obos.%I TO postgres, service_role USING (true) WITH CHECK (true)',
      t
    );
  END LOOP;
END;
$$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA obos TO postgres, service_role;

CREATE TABLE obos.stok_opname (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_setoran_buku bigint NOT NULL REFERENCES obos.setoran_buku (id),
  tanggal date NOT NULL,
  id_barang text NOT NULL REFERENCES obos.barang (id_barang),
  nama_barang text NOT NULL,
  stok_awal numeric(14, 4) NOT NULL DEFAULT 0,
  qty_masuk numeric(14, 4) NOT NULL DEFAULT 0,
  qty_packed numeric(14, 4) NOT NULL DEFAULT 0,
  qty_batal numeric(14, 4) NOT NULL DEFAULT 0,
  qty_retur numeric(14, 4) NOT NULL DEFAULT 0,
  stok_hitung numeric(14, 4) GENERATED ALWAYS AS (
    stok_awal + qty_masuk - qty_packed + qty_batal + qty_retur
  ) STORED,
  stok_fisik numeric(14, 4),
  selisih numeric(14, 4) GENERATED ALWAYS AS (
    stok_fisik - (stok_awal + qty_masuk - qty_packed + qty_batal + qty_retur)
  ) STORED,
  dicek_stok_oleh text,
  putusan text,
  nilai_putusan integer,
  harga_beli_putusan integer,
  qty_selisih_putusan numeric(14, 4),
  kasbon_email text,
  kasbon_nama text,
  waktu_putusan timestamptz,
  CONSTRAINT stok_opname_nama_chk CHECK (btrim(nama_barang) <> ''),
  CONSTRAINT stok_opname_angka_chk CHECK (
    stok_awal >= 0
    AND qty_masuk >= 0
    AND qty_packed >= 0
    AND qty_batal >= 0
    AND qty_retur >= 0
    AND (stok_fisik IS NULL OR stok_fisik >= 0)
  ),
  CONSTRAINT stok_opname_putusan_chk CHECK (
    putusan IS NULL
    OR (
      putusan IN ('kasbon', 'beban', 'margin_plus')
      AND nilai_putusan IS NOT NULL
      AND nilai_putusan >= 0
      AND harga_beli_putusan IS NOT NULL
      AND harga_beli_putusan >= 0
      AND (
        putusan <> 'kasbon'
        OR (
          kasbon_email IS NOT NULL
          AND btrim(kasbon_email) <> ''
          AND kasbon_nama IS NOT NULL
          AND btrim(kasbon_nama) <> ''
        )
      )
    )
  ),
  CONSTRAINT stok_opname_sku_buku UNIQUE (id_setoran_buku, id_barang)
);


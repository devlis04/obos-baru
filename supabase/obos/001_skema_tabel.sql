-- Skema obos baru: drop bekas (kanon + obos lama), tabel inti, seed konfigurasi.
-- SQL Editor sebagai postgres. public tidak diubah. Tidak migrasi. Tidak untuk API.
-- Jangan taruh obos di Extra Schemas API.
-- Ulangi = DROP CASCADE: semua isi obos hilang.

DROP SCHEMA IF EXISTS kanon CASCADE;
DROP SCHEMA IF EXISTS obos CASCADE;

CREATE SCHEMA obos;
COMMENT ON SCHEMA obos IS
  'Skema kanonik app baru. Kosong dari histori. public = app hidup.';

REVOKE ALL ON SCHEMA obos FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA obos TO postgres, service_role;
GRANT CREATE ON SCHEMA obos TO postgres;

-- 1. Tanpa FK ke tabel obos lain
CREATE TABLE obos.users (
  email text PRIMARY KEY,
  nama text NOT NULL,
  peran text NOT NULL,
  rute text NOT NULL DEFAULT '',
  is_login boolean NOT NULL DEFAULT false,
  kunci_hp text,
  sesi_login text,
  CONSTRAINT users_email_chk CHECK (btrim(email) <> ''),
  CONSTRAINT users_nama_chk CHECK (btrim(nama) <> ''),
  CONSTRAINT users_peran_chk CHECK (peran IN ('sales', 'gudang', 'admin', 'pengirim'))
);

CREATE UNIQUE INDEX users_rute_satu_akun_uidx
  ON obos.users (lower(btrim(rute)))
  WHERE btrim(rute) <> '';

CREATE OR REPLACE FUNCTION obos.users_rapikan()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.email := lower(btrim(NEW.email));
  NEW.nama := btrim(NEW.nama);
  NEW.peran := lower(btrim(NEW.peran));
  NEW.rute := btrim(COALESCE(NEW.rute, ''));
  NEW.kunci_hp := nullif(btrim(NEW.kunci_hp), '');
  NEW.sesi_login := nullif(btrim(NEW.sesi_login), '');
  RETURN NEW;
END;
$$;

CREATE TRIGGER users_rapikan_trg
  BEFORE INSERT OR UPDATE ON obos.users
  FOR EACH ROW EXECUTE PROCEDURE obos.users_rapikan();

